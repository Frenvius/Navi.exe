use windows::Win32::Graphics::Direct2D::Common::D2D1_COLOR_F;

macro_rules! palette {
    ($($name:ident: ($dark:expr, $light:expr),)*) => {
        #[allow(dead_code)]
        #[derive(Clone, Copy)]
        pub struct Theme {
            $(pub $name: D2D1_COLOR_F,)*
        }

        impl Theme {
            pub fn system() -> Self {
                let dark = crate::shell::theme::dark();
                let mut theme = Self::new(dark);
                theme.accent = color((crate::shell::nav::accent_fill(dark) << 8) | 255);
                theme
            }

            pub(super) fn new(dark: bool) -> Self {
                Self {
                    $($name: color(if dark { $dark } else { $light }),)*
                }
            }
        }
    };
}

const fn color(rgba: u32) -> D2D1_COLOR_F {
    D2D1_COLOR_F {
        r: (rgba >> 24) as f32 / 255.0,
        g: ((rgba >> 16) & 255) as f32 / 255.0,
        b: ((rgba >> 8) & 255) as f32 / 255.0,
        a: (rgba & 255) as f32 / 255.0,
    }
}

